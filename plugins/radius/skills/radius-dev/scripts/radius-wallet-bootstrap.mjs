#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync, chmodSync } from 'node:fs';
import { join, resolve } from 'node:path';

const TESTNET = {
  network: 'testnet',
  chainId: '72344',
  rpcUrl: 'https://rpc.testnet.radiustech.xyz',
};

function usage(exitCode = 0) {
  const out = exitCode === 0 ? console.log : console.error;
  out(`Usage: node radius-wallet-bootstrap.mjs --name <wallet-name> [--network testnet] [--force]

Creates or reuses a local ignored env file for an agent-created Radius testnet wallet.
The private key is written to .radius/wallets/<name>.env and is never printed.

Options:
  --name <wallet-name>   Required. File-safe wallet name, e.g. radius-demo
  --network testnet      Optional. Only testnet wallet creation is supported
  --force                Replace an existing env file with a new wallet
  --help                 Show this help
`);
  process.exit(exitCode);
}

function parseArgs(argv) {
  const args = { network: 'testnet', force: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--help' || arg === '-h') usage(0);
    if (arg === '--force') {
      args.force = true;
      continue;
    }
    if (arg === '--name' || arg === '-n') {
      args.name = argv[++i];
      continue;
    }
    if (arg === '--network') {
      args.network = argv[++i];
      continue;
    }
    console.error(`Unknown argument: ${arg}`);
    usage(1);
  }
  if (!args.name) {
    console.error('Missing required --name <wallet-name>');
    usage(1);
  }
  if (!/^[a-zA-Z0-9._-]+$/.test(args.name)) {
    console.error('Wallet name must contain only letters, numbers, dot, underscore, or dash');
    process.exit(1);
  }
  if (args.network !== 'testnet') {
    console.error('Refusing to create agent-managed wallets outside Radius testnet');
    process.exit(1);
  }
  return args;
}

function parseEnvFile(path) {
  const env = {};
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    if (!line || line.trimStart().startsWith('#')) continue;
    const idx = line.indexOf('=');
    if (idx === -1) continue;
    env[line.slice(0, idx)] = line.slice(idx + 1);
  }
  return env;
}

function assertExistingEnv(path, env) {
  const missing = ['PRIVATE_KEY', 'RADIUS_PRIVATE_KEY', 'OWNER', 'PAYMENT_ADDRESS'].filter((key) => !env[key]);
  if (missing.length) {
    console.error(`Existing wallet env is missing required keys: ${missing.join(', ')}`);
    console.error(`Delete ${path} or rerun with --force to create a new testnet wallet.`);
    process.exit(1);
  }
}

function makeWallet() {
  let output;
  try {
    output = execFileSync('cast', ['wallet', 'new', '--json'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
  } catch (error) {
    console.error('Failed to run `cast wallet new --json`. Install Foundry and ensure `cast` is on PATH.');
    if (error.stderr) console.error(String(error.stderr).trim());
    process.exit(1);
  }

  let parsed;
  try {
    parsed = JSON.parse(output);
  } catch {
    console.error('Failed to parse `cast wallet new --json` output.');
    process.exit(1);
  }

  const wallet = Array.isArray(parsed) ? parsed[0] : parsed;
  const address = wallet?.address;
  const privateKey = wallet?.private_key ?? wallet?.privateKey;
  if (!/^0x[a-fA-F0-9]{40}$/.test(address ?? '') || !/^0x[a-fA-F0-9]{64}$/.test(privateKey ?? '')) {
    console.error('`cast wallet new --json` did not return a valid address and private key.');
    process.exit(1);
  }

  return { address, privateKey };
}

function writeWalletEnv(path, wallet) {
  const body = [
    '# Radius agent-created testnet wallet',
    '# Generated by radius-wallet-bootstrap.mjs. Do not commit this file.',
    `PRIVATE_KEY=${wallet.privateKey}`,
    `RADIUS_PRIVATE_KEY=${wallet.privateKey}`,
    `OWNER=${wallet.address}`,
    `PAYMENT_ADDRESS=${wallet.address}`,
    `RADIUS_NETWORK=${TESTNET.network}`,
    `RADIUS_CHAIN_ID=${TESTNET.chainId}`,
    `RADIUS_RPC_URL=${TESTNET.rpcUrl}`,
    '',
  ].join('\n');
  writeFileSync(path, body, { mode: 0o600, flag: 'w' });
  chmodSync(path, 0o600);
}

function printResult({ status, envPath, address }) {
  console.log(`status=${status}`);
  console.log(`env_file=${envPath}`);
  console.log(`OWNER=${address}`);
  console.log(`PAYMENT_ADDRESS=${address}`);
  console.log(`RADIUS_NETWORK=${TESTNET.network}`);
  console.log(`RADIUS_CHAIN_ID=${TESTNET.chainId}`);
  console.log(`RADIUS_RPC_URL=${TESTNET.rpcUrl}`);
  console.log('private_key=stored_not_printed');
}

const args = parseArgs(process.argv.slice(2));
const root = resolve(process.cwd(), '.radius');
const walletsDir = join(root, 'wallets');
const envPath = join(walletsDir, `${args.name}.env`);
const existedBefore = existsSync(envPath);

mkdirSync(walletsDir, { recursive: true, mode: 0o700 });
chmodSync(root, 0o700);
chmodSync(walletsDir, 0o700);
writeFileSync(join(root, '.gitignore'), '*\n', { mode: 0o600, flag: 'w' });
chmodSync(join(root, '.gitignore'), 0o600);

if (existedBefore && !args.force) {
  const env = parseEnvFile(envPath);
  assertExistingEnv(envPath, env);
  printResult({ status: 'reused', envPath, address: env.OWNER });
  process.exit(0);
}

const wallet = makeWallet();
writeWalletEnv(envPath, wallet);
printResult({ status: existedBefore && args.force ? 'replaced' : 'created', envPath, address: wallet.address });
